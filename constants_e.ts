// --- Player Generator ---
const generatePlayer = (role: 'GK' | 'DEF' | 'MID' | 'FWD', baseRating: number, teamId: string, index: number): Player => {
  let rating = Math.floor(baseRating + (Math.random() * 8) - 4);
  if (rating > 85) rating = 85; 
  if (rating < 55) rating = 55;

  const age = Math.floor(17 + Math.random() * 5); // 17-21
  const fname = UK_FIRST_NAMES[Math.floor(Math.random() * UK_FIRST_NAMES.length)];
  const lname = UK_LAST_NAMES[Math.floor(Math.random() * UK_LAST_NAMES.length)];

  return {
    id: `${teamId}-${role}-${index}`,
    name: `${fname} ${lname}`,
    position: role,
    rating,
    age,
    goals: 0,
    assists: 0,
    matchesPlayed: 0,
    yellowCards: 0,
    redCards: 0,
    matchesBanned: 0,
    injury: 0,
    form: 6 + Math.floor(Math.random() * 4)
  };
};

// Helper to construct squad with real players and reserve depth
const buildTeamSquad = (teamId: string, realPlayers: Partial<Player>[], att: number, mid: number, def: number): Player[] => {
  const squad: Player[] = realPlayers.map((rp, i) => ({
    id: `REAL-${teamId}-${rp.name?.replace(/[^a-zA-Z0-9]/g, '')}-${i}`,
    name: rp.name || 'Unknown',
    position: rp.position || 'MID',
    rating: rp.rating || 75,
    age: rp.age || 25,
    goals: 0,
    assists: 0,
    matchesPlayed: 0,
    yellowCards: 0,
    redCards: 0,
    matchesBanned: 0,
    injury: 0,
    form: 7 + Math.floor(Math.random() * 3)
  }));

  // >= 20 人就不需要生成任何随机虚构球员
  if (squad.length >= 20) {
    return squad.sort((a, b) => b.rating - a.rating);
  }

  // 若少于 20 人，补足至 20 人（优先保证至少 2 名门将）
  let reserveIdx = 0;
  const gks = squad.filter(p => p.position === 'GK').length;
  if (gks < 2) {
    for (let i = gks; i < 2; i++) squad.push(generatePlayer('GK', def - 8, teamId, reserveIdx++));
  }

  while (squad.length < 20) {
    squad.push(generatePlayer('MID', mid - 8, teamId, reserveIdx++));
  }

  return squad.sort((a, b) => b.rating - a.rating);
};

const createTeam = (
  id: string, name: string, league: LeagueLevel, 
  att: number, mid: number, def: number, 
  color: string, logo: any,
  realPlayers: Partial<Player>[] = []
): Team => {
  const players = buildTeamSquad(id, realPlayers, att, mid, def);
  return {
    id, name, league, att, mid, def, color, logo,
    points: 0, played: 0, won: 0, drawn: 0, lost: 0, gf: 0, ga: 0,
    players
  };
};

